class Parsing(unittest.TestCase):
    def test_claude_transcript(self):
        with tempfile.NamedTemporaryFile('w', suffix='.jsonl', delete=False) as file:
            file.write(CLAUDE)
        self.addCleanup(os.unlink, file.name)
        self.assertEqual(w.claude_conversation(file.name), EXPECTED_CLAUDE)

    def test_queued_message_seen_twice_counts_once_either_order(self):
        text = line(type='user', message={'content': 'same words'}) + \
            line(type='attachment', attachment={'type': 'queued_command', 'origin': {'kind': 'human'}, 'prompt': 'same words'}) + \
            line(type='user', message={'content': 'same words'})
        with tempfile.NamedTemporaryFile('w', suffix='.jsonl', delete=False) as file:
            file.write(text)
        self.addCleanup(os.unlink, file.name)
        # Typed, then delivered once more as an attachment (dropped), then typed again on purpose (kept).
        self.assertEqual(w.claude_conversation(file.name), [['You', ['same words', 'same words']]])

    def test_codex_server_items(self):
        self.assertEqual(w.codex_entries(CODEX_ITEMS), EXPECTED_CODEX)

    def test_codex_session_file_items(self):
        self.assertEqual(w.codex_entries(ROLLOUT_ITEMS), EXPECTED_CODEX)

    def test_render(self):
        text = w.render_conversation('Codex', str(Path.home() / 'site'), EXPECTED_CODEX)
        body = text.split('\n', 1)[1]
        self.assertTrue(text.startswith('Conversation with Codex in ~/site (copied '))
        self.assertEqual(body, '\nYou:\nMake the header sticky\n[image]\n\nCodex:\nI will look at the header.\n'
                               '  • ran: rg header\n  • edited: ~/site/header.css\n  • searched the web for: css sticky\n'
                               '  • viewed image: shot.png\n\n(The conversation was compacted here.)\n\nCodex:\nDone: the header sticks.\n')

    def test_tool_lines_are_tidy(self):
        """Pasted into Claude Code, an image path becomes an attachment and breaks the text up,
        so viewed images are named by file name only. Plumbing tools are left out, and repeated
        identical lines are folded into one."""
        home = str(Path.home())
        tools = [('ToolSearch', {'query': 'select:Monitor'}), ('Read', {'file_path': '/tmp/x/sheet.PNG'}),
                 ('Read', {'file_path': home + '/a.py'}), ('Read', {'file_path': home + '/a.py'}),
                 ('Read', {'file_path': home + '/a.py'}), ('Monitor', {'description': 'suite progress'}),
                 ('TaskStop', {'task_id': 'x'}), ('Read', {'file_path': home + '/a.py'})]
        text = line(type='user', message={'content': 'go'}) + ''.join(
            line(type='assistant', message={'content': [{'type': 'tool_use', 'name': n, 'input': i}]}) for n, i in tools)
        with tempfile.NamedTemporaryFile('w', suffix='.jsonl', delete=False) as file:
            file.write(text)
        self.addCleanup(os.unlink, file.name)
        rendered = w.render_conversation('Claude', home, w.claude_conversation(file.name))
        self.assertEqual(rendered.split('\n', 1)[1], '\nYou:\ngo\n\nClaude:\n  • viewed image: sheet.PNG\n'
                         '  • read: ~/a.py (×3)\n  • watched: suite progress\n  • stopped a background task\n'
                         '  • read: ~/a.py\n')
        codex = w.render_conversation('Codex', home, w.codex_entries(
            [{'type': 'imageView', 'path': '/home/x/shot one.jpeg'}, {'type': 'ImageView', 'path': '/tmp/b.webp'}]))
        self.assertIn('  • viewed image: shot one.jpeg\n  • viewed image: b.webp\n', codex)
        self.assertNotRegex(rendered + codex, r'/\S*\.(?i:png|jpe?g|webp)')

    def test_tool_line_is_one_short_line(self):
        self.assertEqual(w.tool_line('ran', '\n\n  ' + 'x' * 300 + '\nmore'), '  • ran: ' + 'x' * 159 + '…')


class Pane(unittest.TestCase):
    """Copy everything end to end: a real tmux server, a stand-in wl-copy, real panes."""

    def setUp(self):
        self.dir = Path(tempfile.mkdtemp(prefix='copy-everything-'))
        self.addCleanup(shutil.rmtree, self.dir, ignore_errors=True)
        self.socket = str(self.dir / 'tmux.sock')
        self.addCleanup(subprocess.run, ['tmux', '-S', self.socket, 'kill-server'], capture_output=True)
        bin_dir = self.dir / 'bin'
        bin_dir.mkdir()
        self.clip = self.dir / 'clipboard.txt'
        (bin_dir / 'wl-copy').write_text(f'#!/bin/sh\ncat > {self.clip}\n')
        for path in bin_dir.iterdir():
            path.chmod(0o755)
        self.old_path, self.old_socket, self.old_sessions = os.environ['PATH'], w.SOCKET, w.CODEX_SESSIONS
        os.environ['PATH'] = f'{bin_dir}:{self.old_path}'
        w.SOCKET = self.socket
        w.CODEX_SESSIONS = self.dir / 'sessions'
        self.addCleanup(self.restore)
        config = self.dir / 'tmux.conf'
        config.write_text('set -g history-limit 50000\n')  # as in workspace.conf and agent-terminal.conf
        subprocess.run(['tmux', '-S', self.socket, '-f', str(config), 'new-session', '-d', '-x', '80', '-y', '24',
                        '-c', str(Path.home()), 'bash --norc --noprofile'], check=True)
        self.pane = subprocess.run(['tmux', '-S', self.socket, 'display', '-p', '#{pane_id}'],
                                   capture_output=True, text=True, check=True).stdout.strip()

    def restore(self):
        os.environ['PATH'], w.SOCKET, w.CODEX_SESSIONS = self.old_path, self.old_socket, self.old_sessions

    def agent(self, name, before=''):
        # A stand-in that tmux reports as the agent: its first argument is the agent's name.
        self.keys(before + "printf '\\033[?1049h  visible agent screen\\n'; exec -a " + name + ' sleep 600')
        self.assertTrue(self.wait_for(lambda: self.command() == name))

    def keys(self, text):
        subprocess.run(['tmux', '-S', self.socket, 'send-keys', '-t', self.pane, '-l', text], check=True)
        subprocess.run(['tmux', '-S', self.socket, 'send-keys', '-t', self.pane, 'Enter'], check=True)

    def wait_for(self, predicate, seconds=10):
        deadline = time.monotonic() + seconds
        while time.monotonic() < deadline:
            if predicate():
                return True
            time.sleep(0.1)
        return False

    def command(self):
        return subprocess.run(['tmux', '-S', self.socket, 'display', '-p', '-t', self.pane, '#{pane_current_command}'],
                              capture_output=True, text=True).stdout.strip()

    def copied(self):
        self.clip.unlink(missing_ok=True)
        w.copy_everything(self.pane)
        self.assertTrue(self.wait_for(self.clip.exists, 5), 'nothing reached the clipboard')
        return self.clip.read_text()

    def test_shell_history_beyond_the_screen(self):
        self.keys("PS1='$ '; clear")
        self.keys('seq 1 3000; echo ' + 'w' * 150)
        def finished():
            lines = subprocess.run(['tmux', '-S', self.socket, 'capture-pane', '-p', '-J', '-t', self.pane, '-S', '-'],
                                   capture_output=True, text=True).stdout.rstrip().splitlines()
            return 'w' * 150 in lines and lines[-1] == '$'
        self.assertTrue(self.wait_for(finished))
        text = self.copied()
        lines = text.splitlines()
        self.assertIn('$ seq 1 3000; echo ' + 'w' * 150, lines)   # the long command, unwrapped
        self.assertEqual(lines[lines.index('1'):lines.index('3000') + 1], [str(n) for n in range(1, 3001)])
        self.assertIn('w' * 150, lines)                            # the long output line, unwrapped
        self.assertTrue(text.endswith('\n') and not text.endswith('\n\n'))
        self.assertEqual(text, text.lstrip('\n'))

    def test_claude_pane_copies_conversation(self):
        transcript = self.dir / 'session.jsonl'
        transcript.write_text(CLAUDE)
        self.agent('claude')
        w.option(self.pane, '@workspace_transcript', transcript)
        text = self.copied()
        self.assertTrue(text.startswith('Conversation with Claude in ~ (copied '))
        self.assertIn('\nYou:\nFix the login bug please\n', text)
        for hidden in ('HUGE TOOL OUTPUT', 'secret thoughts', 'SUBAGENT', 'REMINDER', 'SUMMARY', 'task-notification'):
            self.assertNotIn(hidden, text)

    def test_claude_without_transcript_copies_the_screen(self):
        self.agent('claude')
        self.assertIn('visible agent screen', self.copied())

    def test_codex_pane_by_thread(self):
        thread = '01a1-test-thread'
        folder = w.CODEX_SESSIONS / '2026/10/11'
        folder.mkdir(parents=True)
        records = [{'type': 'session_meta', 'payload': {'id': thread}},
                   {'type': 'response_item', 'payload': {'type': 'message', 'role': 'user', 'content': [{'type': 'input_text', 'text': '# AGENTS.md instructions'}]}}]
        records += [{'type': 'event_msg', 'payload': {'type': 'item_completed', 'item': item}} for item in ROLLOUT_ITEMS]
        (folder / f'rollout-2026-10-11T06-00-00-{thread}.jsonl').write_text(''.join(json.dumps(r) + '\n' for r in records))
        self.agent('codex')
        w.option(self.pane, '@workspace_thread', thread)
        text = self.copied()
        self.assertIn('\nYou:\nMake the header sticky\n[image]\n\nCodex:\nI will look at the header.\n  • ran: rg header\n', text)
        self.assertNotIn('AGENTS.md', text)

    def test_codex_pane_by_open_session_file(self):
        """A Codex launched on its own (not on the shared server) is found by the file it has open."""
        folder = w.CODEX_SESSIONS / '2026/10/11'
        folder.mkdir(parents=True)
        session = folder / 'rollout-2026-10-11T06-00-00-embedded.jsonl'
        session.write_text(json.dumps({'type': 'event_msg', 'payload': {'type': 'item_completed', 'item':
                                       {'type': 'UserMessage', 'content': [{'type': 'text', 'text': 'from the open file'}]}}}) + '\n')
        self.agent('codex', before=f"exec 9<'{session}'; ")
        self.assertIn('You:\nfrom the open file', self.copied())


